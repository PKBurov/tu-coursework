#define CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <conio.h>
#include <stdlib.h>
#include <windows.h>
#include "func.h"
#include "menu.h"

//---------------------------------------------------------------------------------------------------------------------------
char *txt_menu[]=
{
	  "-----ПРОГРАМА ТЕКСТОВ ФАЙЛ-----",
		"Показване съдържанието на текстов файл............................",
		"Намиране на минималното и максималното числа в масива.............",
		"Изчисляване на средно-аритметичната стойност на числата в масива..",
		"Намиране сумата и броя на числата в зададен интервал от масива....",
		"Сортиране на числата от масива във възходящ ред...................",
		"Изход.............................................................",
		NULL
};
//----------------------------------------------------------------------------------------------------------------------------

int main()
{
	short mode;
    int *ptr=0;
    FILE *fp=NULL;
    int i=0, size=0, num=0,digit;
    char filename[50];
//-----------------------------------------------------------------------------------------------------------------------
	SetConsoleOutputCP(1251);
	SetConsoleCP(1251);
//------------------------------------------------------------------------------------------------------------------------
	printf("Въведете името на входния файл:");
	scanf("%s", filename);
	fp = fopen(filename, "r");
	if (fp == NULL)
	{
		printf("Cannot open file \n");
		exit(0);
	}
//---------------------------------------------------------------------------------------------------------------------------
	//Четене от текстов файл на цели числа и запис в динамичен масив, като се следи за препълване
    while(fscanf(fp,"%d",&digit)==1)
        {
            ptr = include(digit, ptr, &size, &num);
            if(ptr == NULL) {
                printf("Memory allocation error!");
                fclose(fp);
                return 1;
            }
        }
	printf("\nСъздаден е динамичен масив.\n");
	system ("pause");

	printf("\nСъдържанието на масива е:\n");
         for(i=0; i<num; i++)
		 {
			 printf(" %d", ptr[i]);
		 } 
		 system("PAUSE");
//-----------------------------------------------------------------------------------------------------------------------------
	do{
			 system("cls");
			 mode=menu(txt_menu);
			 switch (mode)
			 {
//------------------------------------------------------------------------------------------------------------------------------
				 case 1: print_text_file(); break;

				 case 2:
					 sort(ptr , num);
						printf("\nМаксимум: %d\n", ptr[0]);
						printf("Минимум: %d\n", ptr[num-1]);
					 system("pause");
					 break;

				 case 3: 
					 average(ptr, num);
					 system("pause");
					 break;

				 case 4: 
					 interval(ptr, num);
					 system("pause");
					 break;

				case 5: sort(ptr , num);
					 printf("\nМасивът е сортиран!\n");
					 system("pause");
					 break;
		

			}
	}while (mode != 6);
	_fcloseall();
	free(ptr);
	return NULL;
}